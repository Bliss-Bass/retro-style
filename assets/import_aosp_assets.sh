# Import the legacy tablet / Holo / KitKat artwork and fonts from AOSP
# (Apache 2.0) into assets/aosp/<tag>/ and record where every file came from
# in assets/ASSET_SOURCES.md. Nothing here may come from TabletKat: it has no
# license.
#
# Usage: assets/import_aosp_assets.sh [workdir]
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
work="${1:-/tmp/aosp-legacy}"
remote="https://android.googlesource.com/platform/frameworks/base"
out="$here/aosp"
sources="$here/ASSET_SOURCES.md"

fetch() {
	local tag=$1
	[ -d "$work/$tag/.git" ] && return 0
	mkdir -p "$work"
	git clone -q --filter=blob:none --no-checkout --depth 1 -b "$tag" "$remote" "$work/$tag"
	git -C "$work/$tag" sparse-checkout set --no-cone 'packages/SystemUI/res/' 'data/fonts/' 'NOTICE'
	git -C "$work/$tag" checkout -q "$tag"
}

# tag  source-path  destination (relative to assets/aosp/<tag>/)
manifest() {
	local t41=android-4.1.2_r2 t44=android-4.4.4_r2
	local r41=packages/SystemUI/res r44=packages/SystemUI/res
	local f
	# Android 4.1 tablet system bar: notification panel and clock header.
	for f in notification_panel_bg.9.png notify_panel_clock_bg_normal.9.png notify_panel_clock_bg_pressed.9.png; do
		echo "$t41 $r41/drawable-sw720dp-xhdpi/$f res/drawable-xhdpi/$f"
	done
	# Android 4.1 tablet nav glyphs and IME button.
	for f in ic_sysbar_back ic_sysbar_back_ime ic_sysbar_home ic_sysbar_recent ic_sysbar_menu; do
		echo "$t41 $r41/drawable-sw600dp-xhdpi/$f.png res/drawable-xhdpi/tablet_$f.png"
	done
	echo "$t41 $r41/drawable-sw720dp-xhdpi/ic_sysbar_ime_default.png res/drawable-xhdpi/tablet_ic_sysbar_ime_default.png"
	# Android 4.1 tablet quick settings row icons.
	for f in ic_sysbar_airplane_on ic_sysbar_wifi_on ic_sysbar_rotate_on ic_sysbar_brightness ic_sysbar_quicksettings ic_notification_open ic_notification_dnd; do
		echo "$t41 $r41/drawable-xhdpi/$f.png res/drawable-xhdpi/$f.png"
	done
	# Android 4.1 tablet (blue Holo) status icons.
	for f in 0 15 28 43 57 71 85 100; do
		echo "$t41 $r41/drawable-sw720dp-xhdpi/stat_sys_battery_$f.png res/drawable-xhdpi/stat_sys_battery_$f.png"
		echo "$t41 $r41/drawable-sw720dp-xhdpi/stat_sys_battery_charge_anim$f.png res/drawable-xhdpi/stat_sys_battery_charge_anim$f.png"
	done
	for f in 0 1 2 3 4; do
		echo "$t41 $r41/drawable-sw720dp-xhdpi/stat_sys_signal_${f}_fully.png res/drawable-xhdpi/stat_sys_signal_${f}_fully.png"
	done
	for f in 1 2 3 4; do
		echo "$t41 $r41/drawable-sw720dp-xhdpi/stat_sys_wifi_signal_${f}_fully.png res/drawable-xhdpi/stat_sys_wifi_signal_${f}_fully.png"
	done
	for f in stat_sys_wifi_signal_0 stat_sys_wifi_signal_null stat_sys_signal_null stat_sys_signal_flightmode stat_sys_data_bluetooth stat_sys_data_bluetooth_connected; do
		echo "$t41 $r41/drawable-sw720dp-xhdpi/$f.png res/drawable-xhdpi/$f.png"
	done
	# KitKat 4.4 nav glyphs (the thin outline look) and phone QS icons used for
	# the rows 4.1 had no icon for.
	for f in ic_sysbar_back ic_sysbar_back_ime ic_sysbar_home ic_sysbar_recent ic_sysbar_menu; do
		echo "$t44 $r44/drawable-xxhdpi/$f.png res/drawable-xxhdpi/kitkat_$f.png"
	done
	for f in ic_qs_bluetooth_on ic_qs_bluetooth_off ic_qs_location_on ic_qs_location_off ic_qs_airplane_on ic_qs_airplane_off ic_qs_brightness_auto_on ic_qs_brightness_auto_off ic_qs_rotation_locked ic_qs_settings; do
		echo "$t44 $r44/drawable-xhdpi/$f.png res/drawable-xhdpi/$f.png"
	done
	# KitKat Roboto (Apache 2.0).
	for f in Roboto-Thin Roboto-Light Roboto-Regular Roboto-Bold Roboto-Italic Roboto-LightItalic Roboto-ThinItalic Roboto-BoldItalic; do
		echo "$t44 data/fonts/$f.ttf fonts/$f.ttf"
	done
}

fetch android-4.1.2_r2
fetch android-4.4.4_r2

{
	echo "# AOSP asset sources"
	echo
	echo "Generated by \`assets/import_aosp_assets.sh\`. Every file below is copied unmodified from"
	echo "AOSP \`platform/frameworks/base\` (Apache License 2.0; see the NOTICE files next to each tag)."
	echo "No artwork or code comes from TabletKat / TabletKat Revival."
	echo
	echo "| File | AOSP tag | AOSP path | Git blob |"
	echo "|---|---|---|---|"
} > "$sources"

manifest | while read -r tag src dst; do
	mkdir -p "$out/$tag/$(dirname "$dst")"
	cp "$work/$tag/$src" "$out/$tag/$dst"
	blob=$(git -C "$work/$tag" rev-parse "HEAD:$src")
	echo "| \`aosp/$tag/$dst\` | \`$tag\` | \`$src\` | \`${blob:0:12}\` |" >> "$sources"
done

for tag in android-4.1.2_r2 android-4.4.4_r2; do
	cp "$work/$tag/NOTICE" "$out/$tag/NOTICE"
done
[ -f "$work/android-4.4.4_r2/data/fonts/NOTICE" ] && cp "$work/android-4.4.4_r2/data/fonts/NOTICE" "$out/android-4.4.4_r2/fonts/NOTICE"

echo "imported $(($(wc -l < "$sources") - 7)) files into $out"
