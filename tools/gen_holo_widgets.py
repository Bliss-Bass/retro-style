"""Generate the KitKat framework overlay styles from framework-res sources.

Every Widget/TextAppearance/AlertDialog.DeviceDefault style that has a Holo
counterpart is re-parented to it, so apps and system UI that resolve widgets
through DeviceDefault get Holo widgets while the KitKat style is enabled.
Theme.DeviceDefault itself is left alone: SystemUI needs its newer
materialColor* attributes.

Usage: gen_holo_widgets.py <frameworks/base/core/res/res/values> <out styles.xml>
"""
import re
import sys

# DeviceDefault styles with no same-named Holo style.
MANUAL = {
    "Widget.DeviceDefault.Button.Colored": "Widget.Holo.Button",
    "Widget.DeviceDefault.Button.Borderless.Colored": "Widget.Holo.Button.Borderless",
    "Widget.DeviceDefault.Button.ButtonBar.AlertDialog": "Widget.Holo.Button.Borderless.Small",
    "Widget.DeviceDefault.Light.Button.Colored": "Widget.Holo.Light.Button",
    "Widget.DeviceDefault.Light.Button.Borderless.Colored": "Widget.Holo.Light.Button.Borderless",
    "Widget.DeviceDefault.Light.Button.ButtonBar.AlertDialog": "Widget.Holo.Light.Button.Borderless.Small",
    "TextAppearance.DeviceDefault.ListItem": "TextAppearance.Holo.Medium",
    "TextAppearance.DeviceDefault.ListItemSecondary": "TextAppearance.Holo.Small",
}


def styles(path, pattern):
    return re.findall(r'<style name="(%s)"' % pattern, open(path, encoding="utf-8").read())


def main(values_dir, out):
    dd = styles(f"{values_dir}/styles_device_defaults.xml",
                r"(?:Widget|TextAppearance|AlertDialog)\.DeviceDefault[^\"]*")
    holo = set(styles(f"{values_dir}/styles_holo.xml", r"[^\"]*Holo[^\"]*"))
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/gen_holo_widgets.py; do not edit. -->",
        "<resources>",
    ]
    mapped = 0
    for name in dd:
        parent = MANUAL.get(name) or name.replace("DeviceDefault", "Holo")
        if parent not in holo:
            continue
        lines.append(f'    <style name="{name}" parent="@*android:style/{parent}" />')
        mapped += 1
    lines.append("</resources>")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"mapped {mapped} of {len(dd)} DeviceDefault styles to Holo")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
