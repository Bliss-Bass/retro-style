class Pack:
    def __init__(self, pack_id):
        self.id = pack_id
        self.dir = os.path.join(THEMES, pack_id)
        with open(os.path.join(self.dir, "theme.json"), encoding="utf-8") as f:
            self.data = json.load(f)

    def get(self, *path, default=None):
        node = self.data
        for key in path:
            if not isinstance(node, dict) or key not in node:
                return default
            node = node[key]
        return node

    def hand_res(self, target):
        """The pack's hand-made resource folder for [target], when it has one."""
        res = os.path.join(self.dir, target, "res")
        return res if os.path.isdir(res) and any(os.scandir(res)) else None

    def package(self, target):
        return f"org.retro.theme.{self.id}.{target.replace('_', '.')}"

    def module(self, target=None):
        return f"RetroTheme_{self.id}" + (f"_{target}" if target else "")

    def tokens(self, target, values_dir):
        """Resource lines theme.json produces for [target] (empty: nothing generated)."""
        lines = []
        corner = self.get("shape", "corner")
        if corner and target in CORNERS:
            lines += [f'    <dimen name="{n}">{corner}</dimen>' for n in CORNERS[target]]
            if target == "android":
                progress = self.get("shape", "progress", default=corner)
                lines.append(f'    <dimen name="{PROGRESS_CORNER}">{progress}</dimen>')
        if target == "android" and self.get("widgets", default="default") != "default":
            lines += widget_styles(self.get("widgets"), values_dir)
        if target == "font" and self.get("font"):
            for key, name in FONT_RESOURCES.items():
                value = self.get("font", key)
                if value:
                    lines.append(
                        f'    <string name="{name}" translatable="false">{value}</string>'
                    )
        bar = self.get("shell", "bar")
        if target == "launcher3" and bar:
            lines += [f'    <color name="{n}">{bar}</color>' for n in BAR_COLORS]
        return lines

    def targets(self, values_dir):
        """Targets this pack builds an overlay for, in TARGETS order."""
        return [t for t in TARGETS if self.hand_res(t) or self.tokens(t, values_dir)]


def pack_ids(include_template=False):
    ids = []
    for name in sorted(os.listdir(THEMES)):
        if os.path.isfile(os.path.join(THEMES, name, "theme.json")):
            if name.startswith("_") and not include_template:
                continue
            ids.append(name)
    return ids


def validate(pack):
    """Problems with theme.json, as human-readable strings."""
    errors = []
    d = pack.data

    def need(cond, msg):
        if not cond:
            errors.append(msg)

    unknown = set(d) - KEYS
    need(not unknown, f"unknown keys: {', '.join(sorted(unknown))}")
    need(d.get("schema") == SCHEMA_VERSION, f"schema must be {SCHEMA_VERSION}")
    template = pack.id == TEMPLATE
    need(template or d.get("id") == pack.id, f"id must match the folder name ('{pack.id}')")
    need(template or ID_RE.match(str(d.get("id", ""))), "id: lowercase letters, digits and _")
    need(isinstance(d.get("name"), str) and d["name"], "name is required")
    need(isinstance(d.get("summary"), str) and d["summary"], "summary is required")
    need(d.get("category") in CATEGORIES, f"category must be one of {CATEGORIES}")
    need(isinstance(d.get("order", 0), int), "order must be a number")
    need(isinstance(d.get("authors"), list) and d["authors"], "authors: a non-empty list")

    palette = d.get("palette") or {}
    need(palette.get("source") in PALETTE_SOURCES, f"palette.source: one of {PALETTE_SOURCES}")
    if palette.get("source") == "preset":
        need(COLOR_RE.match(str(palette.get("seed", ""))), "palette.seed: #RRGGBB")
        need(palette.get("style") in PALETTE_STYLES, f"palette.style: one of {PALETTE_STYLES}")
    need(set(palette) <= {"source", "seed", "style"}, "palette: only source, seed and style")

    need(d.get("night", "system") in NIGHT_MODES, f"night: one of {NIGHT_MODES}")
    need(isinstance(d.get("black", False), bool), "black: true or false")
    need(not (d.get("black") and d.get("night") == "light"), "black needs night dark or system")
    need(d.get("widgets", "default") in WIDGET_FAMILIES, f"widgets: one of {WIDGET_FAMILIES}")

    font = d.get("font") or {}
    need(set(font) <= FONT_KEYS, f"font: only {sorted(FONT_KEYS)}")
    for key, value in font.items():
        need(value in FONT_FAMILIES, f"font.{key}: '{value}' is not a system font family")

    shape = d.get("shape") or {}
    need(set(shape) <= SHAPE_KEYS, f"shape: only {sorted(SHAPE_KEYS)}")
    for key, value in shape.items():
        need(DIMEN_RE.match(str(value)), f"shape.{key}: a size in dp, like 2dp")

    shell = d.get("shell") or {}
    need(set(shell) <= SHELL_KEYS, f"shell: only {sorted(SHELL_KEYS)}")
    need(shell.get("skin", "stock") in SKINS, f"shell.skin: one of {SKINS}")
    need(shell.get("layout", "stock") in LAYOUTS, f"shell.layout: one of {LAYOUTS}")
    need(isinstance(shell.get("bar_apps", True), bool), "shell.bar_apps: true or false")
    need(shell.get("bar_home", "solid") in BAR_HOME, f"shell.bar_home: one of {BAR_HOME}")
    for key in ("panel", "accent", "bar"):
        if key in shell:
            need(COLOR_RE.match(str(shell[key])), f"shell.{key}: #RRGGBB or #AARRGGBB")
    if "panel" in shell and COLOR_RE.match(str(shell["panel"])):
        # Panel text is white (dark night) or near black (light): keep it readable.
        text = (0xFF, 0xFF, 0xFF) if d.get("night") != "light" else (0x1C, 0x1B, 0x1F)
        ratio = contrast(text, over_wallpaper(shell["panel"]))
        need(ratio >= 4.5, f"shell.panel: text contrast {ratio:.1f}:1 is under 4.5:1")

    for target in TARGETS:
        res = os.path.join(pack.dir, target)
        if os.path.isdir(res) and not os.path.isdir(os.path.join(res, "res")) and not os.path.isfile(
            os.path.join(res, "AndroidManifest.xml")
        ):
            errors.append(f"{target}/ has no res/ folder")
    for name in os.listdir(pack.dir):
        path = os.path.join(pack.dir, name)
        if os.path.isdir(path) and name not in TARGETS:
            errors.append(f"unknown folder {name}/ (targets: {', '.join(TARGETS)})")
    if has_binary_assets(pack) and not os.path.isfile(os.path.join(pack.dir, "SOURCES.md")):
        errors.append("images or fonts need a SOURCES.md saying where each file comes from")
    return errors


def has_binary_assets(pack):
    for root, _, files in os.walk(pack.dir):
        if any(f.endswith((".png", ".webp", ".jpg", ".ttf", ".otf")) for f in files):
            return True
    return False


def srgb_luminance(rgb):
    def channel(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((srgb_luminance(a), srgb_luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def over_wallpaper(color, worst=(0x80, 0x80, 0x80)):
    """A translucent color composited over a mid-grey wallpaper, the worst common case."""
    value = color.lstrip("#")
    alpha = int(value[:2], 16) / 255 if len(value) == 8 else 1.0
    rgb = [int(value[i : i + 2], 16) for i in range(len(value) - 6, len(value), 2)]
    return tuple(round(c * alpha + w * (1 - alpha)) for c, w in zip(rgb, worst))


# --- Generating ------------------------------------------------------------------------------


def manifest(pack, target):
    target_package, category = TARGETS[target]
    theme_category = category == "org.retro.theme"
    label = f"{pack.get('name')} ({target.replace('_', ' ')})"
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER_XML,
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    package="{pack.package(target)}">',
        "    <overlay",
        f'        android:targetPackage="{target_package}"',
        f'        android:category="{category}"',
    ]
    # Theme overlays sit above ThemePicker's priority-1 packs; all stay switchable.
    lines.append(f'        android:priority="{10 if theme_category else 1}"')
    if theme_category:
        lines.append('        android:isStatic="false"')
    lines[-1] += " />"
    lines += [
        f'    <application android:hasCode="false" android:label="{escape(label)}" />',
        "</manifest>",
    ]
    return "\n".join(lines) + "\n"


def escape(text):
    return text.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def generated_values(lines):
    return "\n".join(
        ['<?xml version="1.0" encoding="utf-8"?>', HEADER_XML, "<resources>", *lines, "</resources>"]
    ) + "\n"


def android_bp(pack, targets, values_dir):
    aosp_assets = has_binary_assets(pack)
    license_module = (
        "vendor_retro-style_aosp_assets_license" if aosp_assets else "vendor_retro-style_license"
    )
    out = [
        "// Copyright (C) 2026 Navotpala Tech (Bliss Co-Labs Inc.)",
        "// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-Navotpala-Commercial",
        "",
        "// Generated by tools/theme_tool.py from theme.json; do not edit.",
        "",
        "package {",
        f'    default_applicable_licenses: ["{license_module}"],',
        "}",
        "",
        f"// {pack.get('name')}: {pack.get('summary')}",
        "// Add this one module to PRODUCT_PACKAGES (retro_style.mk does, through themes.mk).",
        "phony {",
        f'    name: "{pack.module()}",',
        "    required: [",
        f'        "{pack.module("json")}",',
        *[f'        "{pack.module(t)}",' for t in targets],
        "    ],",
        "}",
        "",
        "// The RetroStyle app lists the packs it finds in /product/etc/retro-style/themes.",
        "prebuilt_etc {",
        f'    name: "{pack.module("json")}",',
        '    src: "theme.json",',
        f'    filename: "{pack.id}.json",',
        '    sub_dir: "retro-style/themes",',
        "    product_specific: true,",
        "}",
    ]
    for target in targets:
        dirs = []
        if pack.hand_res(target):
            dirs.append(f"{target}/res")
        if pack.tokens(target, values_dir):
            dirs.append(f"{target}/res_gen")
        out += [
            "",
            "runtime_resource_overlay {",
            f'    name: "{pack.module(target)}",',
            f"    resource_dirs: [{', '.join(json.dumps(d) for d in dirs)}],",
        ]
        if len(dirs) > 1:
            out += [
                "    // aapt2 links the second folder as an overlay of the first; let it add the",
                "    // names the first one doesn't have.",
                '    aaptflags: ["--auto-add-overlay"],',
            ]
        out += [
            f'    manifest: "{target}/AndroidManifest.xml",',
            "    // /product overlays may replace resources of targets without <overlayable>.",
            "    product_specific: true,",
            "}",
        ]
    return "\n".join(out) + "\n"


def themes_mk(packs):
    lines = [
        "# Generated by tools/theme_tool.py from themes/*/theme.json; do not edit.",
        "#",
        "# RETRO_THEMES_ALL: every pack id. RETRO_THEME_LAYOUT_<id>: the bottom bar the pack",
        "# suggests (shell.layout), used when the build sets no RETRO_STYLE_LAYOUT.",
        "# RETRO_THEME_SKIN_<id>: the pack's shade skin (shell.skin), for products that pair",
        "# other UI with it (a dock's matching look, for example).",
        "",
        "RETRO_THEMES_ALL := " + " ".join(p.id for p in packs),
        "",
    ]
    lines += [f"RETRO_THEME_LAYOUT_{p.id} := {p.get('shell', 'layout', default='stock')}" for p in packs]
    lines.append("")
    lines += [f"RETRO_THEME_SKIN_{p.id} := {p.get('shell', 'skin', default='stock')}" for p in packs]
    return "\n".join(lines) + "\n"


def expected_files(pack, values_dir):
    """Every generated file for [pack], as {relative path: content}."""
    files = {}
    targets = pack.targets(values_dir)
    for target in targets:
        files[f"{target}/AndroidManifest.xml"] = manifest(pack, target)
        tokens = pack.tokens(target, values_dir)
        if tokens:
            for qualifier in GENERATED_QUALIFIERS.get(target, [""]):
                files[f"{target}/res_gen/values{qualifier}/retro_generated.xml"] = generated_values(tokens)
    files["Android.bp"] = android_bp(pack, targets, values_dir)
    return files


def stale_generated(pack, files):
    """Generated files that exist on disk but are no longer produced."""
    stale = []
    for target in TARGETS:
        rels = [f"{target}/AndroidManifest.xml"]
        gen = os.path.join(pack.dir, target, "res_gen")
        if os.path.isdir(gen):
            rels += [
                f"{target}/res_gen/{d}/retro_generated.xml"
                for d in os.listdir(gen)
                if os.path.isfile(os.path.join(gen, d, "retro_generated.xml"))
            ]
        for rel in rels:
            if os.path.isfile(os.path.join(pack.dir, rel)) and rel not in files:
                stale.append(rel)
    return stale


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def cmd_gen(args):
    ids = args.ids or pack_ids()
    failed = False
    for pack_id in ids:
        pack = Pack(pack_id)
        errors = validate(pack)
        if errors:
            failed = True
            print(f"{pack_id}: not generated:\n  " + "\n  ".join(errors))
            continue
        files = expected_files(pack, args.framework_values)
        for rel in stale_generated(pack, files):
            os.remove(os.path.join(pack.dir, rel))
            gen_dir = os.path.dirname(os.path.join(pack.dir, rel))
            while gen_dir != pack.dir and not os.listdir(gen_dir):
                os.rmdir(gen_dir)
                gen_dir = os.path.dirname(gen_dir)
        for rel, content in files.items():
            write(os.path.join(pack.dir, rel), content)
        print(f"{pack_id}: {', '.join(pack.targets(args.framework_values)) or 'no overlays'}")
    write(os.path.join(THEMES, "themes.mk"), themes_mk([Pack(i) for i in pack_ids()]))
    return 1 if failed else 0


