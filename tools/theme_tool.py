"""Create, generate and check retro-style theme packs (themes/<id>/).

A designer writes themes/<id>/theme.json and, optionally, hand-made resources in
themes/<id>/<target>/res/. This tool writes everything else a pack needs to build:

  <target>/AndroidManifest.xml          the overlay manifest (package, target, category)
  <target>/res_gen/values/retro_generated.xml
                                        resources made from theme.json tokens (corners, widget
                                        family, fonts, bar color)
  Android.bp                            one runtime_resource_overlay per target, the installed
                                        theme.json, and a phony module that groups them
  themes/themes.mk                      the list of packs for retro_style.mk

Generated files are committed, so a ROM build needs no Python. Run `gen` after every change
to a theme.json and commit the result; `check` fails when they're out of date.

Commands:
  list                       show every pack
  new <id> [--from <id>]     start a pack from themes/_template (or a copy of another pack)
  gen [<id> ...]             regenerate the files above (all packs by default)
  check [<id> ...]           validate packs and check every overlaid resource name exists in
                             its target (source tree, plus built APKs with --apks); with
                             --apks, also link every overlay with aapt2 like the build does
  sources <id>               write SOURCES.md for images copied from assets/aosp

Run from anywhere; paths are relative to this repo. See docs/THEME_SPEC.md for the rules.
"""
