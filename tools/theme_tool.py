def git_blob(path):
    return subprocess.run(
        ["git", "hash-object", path], capture_output=True, text=True, check=True
    ).stdout.strip()


def cmd_sources(args):
    """Write themes/<id>/SOURCES.md for images and fonts copied from assets/aosp."""
    imported = {}
    with open(os.path.join(REPO, "assets", "ASSET_SOURCES.md"), encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\| `([^`]+)` \| `([^`]+)` \| `([^`]+)` \|", line)
            if m:
                path = os.path.join(REPO, "assets", m.group(1))
                if os.path.isfile(path):
                    imported[git_blob(path)] = (m.group(2), m.group(3))
    pack = Pack(args.id)
    rows, unknown = [], []
    for root, _, files in sorted(os.walk(pack.dir)):
        for name in sorted(files):
            if not name.endswith((".png", ".webp", ".jpg", ".ttf", ".otf")):
                continue
            path = os.path.join(root, name)
            rel = os.path.relpath(path, pack.dir)
            source = imported.get(git_blob(path))
            if source:
                rows.append(f"| `{rel}` | `{source[0]}` | `{source[1]}` |")
            else:
                unknown.append(rel)
    if unknown:
        print("not copies of assets/aosp files; list their sources in SOURCES.md by hand:")
        print("  " + "\n  ".join(unknown))
        return 1
    lines = [
        f"# {pack.get('name')} pack: image sources",
        "",
        "Every image in this pack is an unmodified copy of an AOSP file (Apache License 2.0; see",
        "`assets/aosp/<tag>/NOTICE`), imported by `assets/import_aosp_assets.sh` and renamed for the",
        "resource it replaces. Nothing comes from TabletKat or other unlicensed themes.",
        "",
        "Written by `tools/theme_tool.py sources " + pack.id + "`.",
        "",
        "| File in this pack | AOSP tag | AOSP path |",
        "|---|---|---|",
        *rows,
    ]
    write(os.path.join(pack.dir, "SOURCES.md"), "\n".join(lines) + "\n")
    print(f"themes/{pack.id}/SOURCES.md: {len(rows)} files")
    return 0


def cmd_new(args):
    if not ID_RE.match(args.id):
        print("id: lowercase letters, digits and _, 2 to 31 characters, starting with a letter")
        return 2
    dest = os.path.join(THEMES, args.id)
    if os.path.exists(dest):
        print(f"themes/{args.id} already exists")
        return 2
    source = os.path.join(THEMES, args.source)
    shutil.copytree(
        source, dest, ignore=shutil.ignore_patterns("Android.bp", "AndroidManifest.xml", "res_gen", "README.md")
    )
    path = os.path.join(dest, "theme.json")
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    data["id"] = args.id
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    print(f"created themes/{args.id} from themes/{args.source}")
    print(f"next: edit themes/{args.id}/theme.json, then tools/theme_tool.py gen {args.id}")
    return 0


