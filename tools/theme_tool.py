def aapt2_path(args):
    for path in (
        args.aapt2,
        os.path.join(REPO, "..", "..", "out", "host", "linux-x86", "bin", "aapt2"),
        os.path.join(REPO, "..", "..", "prebuilts", "sdk", "tools", "linux", "bin", "aapt2"),
        shutil.which("aapt2"),
    ):
        if path and os.path.isfile(path):
            return path
    return None


def apk_resources(aapt2, apk):
    """{"type/name"} defined by [apk], from `aapt2 dump resources`."""
    out = subprocess.run(
        [aapt2, "dump", "resources", apk], capture_output=True, text=True, check=True
    ).stdout
    names = set()
    for line in out.splitlines():
        m = re.match(r"\s+resource 0x[0-9a-f]+ (\S+)", line)
        if m:
            names.add(m.group(1))
    return names


def overlay_resources(res_dirs):
    """{"type/name": file} defined by an overlay's resource folders."""
    names = {}
    for res in res_dirs:
        for folder in os.listdir(res):
            if not os.path.isdir(os.path.join(res, folder)):
                continue
            kind = folder.split("-")[0]
            for name in os.listdir(os.path.join(res, folder)):
                path = os.path.join(res, folder, name)
                if kind != "values":
                    names[f"{kind}/{name.split('.')[0]}"] = path
                    continue
                if not name.endswith(".xml"):
                    continue
                with open(path, encoding="utf-8", errors="replace") as f:
                    text = f.read()
                for tag, rname in re.findall(
                    r'<(dimen|color|string|style|bool|integer|drawable|array|string-array|'
                    r'integer-array|fraction|plurals|attr)\s+name="([^"]+)"',
                    text,
                ):
                    rtype = {"string-array": "array", "integer-array": "array"}.get(tag, tag)
                    names[f"{rtype}/{rname}"] = path
                for rtype, rname in re.findall(r'<item\s+type="(\w+)"\s+name="([^"]+)"', text):
                    names[f"{rtype}/{rname}"] = path
                for rname, rtype in re.findall(r'<item\s+name="([^"]+)"\s+type="(\w+)"', text):
                    names[f"{rtype}/{rname}"] = path
    return names


# Resource folders of each target in the source tree, relative to its root. `check` reads them
# too, so names added by the retro-style patches count before the tree is built.
TARGET_SOURCES = {
    "android": ["frameworks/base/core/res/res"],
    "com.android.systemui": ["frameworks/base/packages/SystemUI/res",
                             "frameworks/base/packages/SystemUI/res-keyguard",
                             "frameworks/base/packages/SystemUI/res-product"],
    "com.android.settings": ["packages/apps/Settings/res", "packages/apps/Settings/res-export",
                             "frameworks/base/packages/SettingsLib/*/res",
                             "frameworks/base/packages/SettingsLib/res"],
    "com.android.launcher3": ["packages/apps/Launcher3/res", "packages/apps/Launcher3/quickstep/res",
                              "packages/apps/Launcher3/go/res"],
}


def source_resources(top, target_package):
    """{"type/name"} defined in the target's source resource folders (empty without a tree)."""
    import glob

    dirs = [d for pattern in TARGET_SOURCES[target_package] for d in glob.glob(os.path.join(top, pattern))]
    names = set()
    for res in dirs:
        if os.path.isdir(res):
            names.update(overlay_resources([res]))
    return names


def internal_references(res_dirs):
    """{"type/name"} the overlay's XML files point at with @type/name (not @android:...)."""
    refs = set()
    for res in res_dirs:
        for root, _, files in os.walk(res):
            for name in files:
                if name.endswith(".xml"):
                    with open(os.path.join(root, name), encoding="utf-8") as f:
                        refs.update(m.replace("@", "", 1) for m in re.findall(r"@[a-z]+/[A-Za-z0-9_.]+", f.read()))
    return refs


def find_apk(apk_dirs, name):
    for d in apk_dirs:
        for root, _, files in os.walk(d):
            if name in files and "/obj/" not in root:
                return os.path.join(root, name)
    return None


def link_overlay(aapt2, framework, pack, target, res_dirs, work):
    compiled = os.path.join(work, f"{pack.id}-{target}")
    os.makedirs(compiled, exist_ok=True)
    flats = []
    for res in res_dirs:
        out = os.path.join(compiled, f"{len(flats)}.zip")
        subprocess.run([aapt2, "compile", "--dir", res, "-o", out], check=True, capture_output=True)
        flats.append(out)
    # The flags Soong's runtime_resource_overlay links with (RuntimeResourceOverlay in
    # build/soong/java/rro.go): the first folder is the base, later ones are -R overlays, and
    # --auto-add-overlay only comes from the module's aaptflags (android_bp adds it).
    cmd = [
        aapt2, "link", "-o", os.path.join(compiled, "overlay.apk"), "-I", framework,
        "--manifest", os.path.join(pack.dir, target, "AndroidManifest.xml"),
        "--min-sdk-version", "36", "--target-sdk-version", "36",
        "--no-resource-deduping", "--no-resource-removal",
    ]
    if len(flats) > 1:
        cmd.append("--auto-add-overlay")
    for i, f in enumerate(flats):
        cmd += (["-R", f] if i else [f])
    return subprocess.run(cmd, capture_output=True, text=True)


def cmd_check(args):
    ids = args.ids or pack_ids(include_template=True)
    aapt2 = aapt2_path(args) if args.apks else None
    if args.apks and not aapt2:
        print("aapt2 not found; pass --aapt2")
        return 2
    target_names = {}
    failed = 0
    work = tempfile.mkdtemp(prefix="retro-theme-check-")
    try:
        for pack_id in ids:
            pack = Pack(pack_id)
            problems = validate(pack)
            if pack_id != TEMPLATE and not problems:
                files = expected_files(pack, args.framework_values)
                for rel, content in files.items():
                    path = os.path.join(pack.dir, rel)
                    if not os.path.isfile(path) or open(path, encoding="utf-8").read() != content:
                        problems.append(f"{rel} is out of date: run tools/theme_tool.py gen {pack_id}")
                for rel in stale_generated(pack, files):
                    problems.append(f"{rel} is no longer generated: run tools/theme_tool.py gen")
                if not problems:
                    problems += check_overlays(args, aapt2, pack, target_names, work)
            if problems:
                failed += 1
                print(f"FAIL {pack_id}\n  " + "\n  ".join(problems))
            else:
                print(f"ok   {pack_id}")
        mk = os.path.join(THEMES, "themes.mk")
        mk_ok = os.path.isfile(mk) and open(mk, encoding="utf-8").read() == themes_mk(
            [Pack(i) for i in pack_ids()]
        )
        if not mk_ok:
            print("FAIL themes/themes.mk is out of date: run tools/theme_tool.py gen")
    finally:
        shutil.rmtree(work, ignore_errors=True)
    print(f"{len(ids) - failed} of {len(ids)} packs ok" if failed else f"all {len(ids)} packs ok")
    return 1 if failed or not mk_ok else 0


def target_resources(args, aapt2, target_package, cache):
    """Names [target_package] defines: its source folders plus, with --apks, its built APK."""
    if target_package not in cache:
        names = source_resources(args.top, target_package)
        apk = find_apk(args.apks, TARGET_APKS[target_package]) if args.apks else None
        if apk:
            names |= apk_resources(aapt2, apk)
        cache[target_package] = names or None
    return cache[target_package]


def check_overlays(args, aapt2, pack, target_names, work):
    """Duplicate names, names the target lacks, and (with --apks) an aapt2 link per overlay."""
    problems = []
    framework = find_apk(args.apks, TARGET_APKS["android"]) if args.apks else None
    if args.apks and not framework:
        return [f"framework-res.apk not found under {args.apks}"]
    for target in pack.targets(args.framework_values):
        res_dirs = [
            d for d in (pack.hand_res(target), os.path.join(pack.dir, target, "res_gen")) if d and os.path.isdir(d)
        ]
        if len(res_dirs) == 2:
            hand, generated = (overlay_resources([d]) for d in res_dirs)
            for name in sorted(set(hand) & set(generated)):
                problems.append(
                    f"{target}: {name} is both in {target}/res and made from theme.json; "
                    "drop one (theme.json wins)"
                )
        if framework:
            result = link_overlay(aapt2, framework, pack, target, res_dirs, work)
            if result.returncode:
                problems.append(f"{target}: aapt2 link failed:\n    " + result.stderr.strip().replace("\n", "\n    "))
                continue
        target_package = TARGETS[target][0]
        names = target_resources(args, aapt2, target_package, target_names)
        if names is None:
            continue
        internal = internal_references(res_dirs)
        for name, path in sorted(overlay_resources(res_dirs).items()):
            # A name the target lacks is fine when the overlay's own files use it (KitKat's tray
            # level-lists point at new kitkat_tray_* images); otherwise it overlays nothing.
            if name not in names and name not in internal:
                rel = os.path.relpath(path, pack.dir)
                problems.append(f"{target}: {name} ({rel}) does not exist in {target_package}")
    return problems


