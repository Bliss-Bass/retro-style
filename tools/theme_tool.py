def family_parent(family, name):
    """The style in [family] a DeviceDefault style should inherit from, before checking it exists."""
    manual = FAMILY_MANUAL[family].get(name)
    if manual:
        return manual
    if family == "holo":
        return name.replace("DeviceDefault", "Holo")
    if family == "material":
        return name.replace("DeviceDefault", "Material")
    # Pre-Holo widgets had no light/dark split: Widget.DeviceDefault.Light.Button -> Widget.Button.
    return name.replace("DeviceDefault.Light.", "").replace("DeviceDefault.", "")


def style_names(path, pattern):
    with open(path, encoding="utf-8") as f:
        return re.findall(r'<style name="(%s)"' % pattern, f.read())


def widget_styles(family, values_dir):
    """`<style>` lines that re-parent DeviceDefault widget and text styles to [family]."""
    device_default = style_names(
        os.path.join(values_dir, "styles_device_defaults.xml"),
        r"(?:Widget|TextAppearance|AlertDialog)\.DeviceDefault[^\"]*",
    )
    available = set(style_names(os.path.join(values_dir, FAMILY_FILES[family]), r"[^\"]*"))
    lines = []
    for name in device_default:
        parent = family_parent(family, name)
        if parent in available:
            lines.append(f'    <style name="{name}" parent="@*android:style/{parent}" />')
    return lines


